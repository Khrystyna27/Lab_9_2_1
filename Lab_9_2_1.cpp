// Обчислити значення виразу
//         | max( (x+y)^2, (x-z)^2 ),   z > 3
//     w = |
//         | min( xy+yz, (zx+yz)^2 ),   z <= 3
// використовуючи макроси та директиви умовної компіляції.
// Значення z задається макросом Z (директива #if працює лише з цілими
// константами); x та y вводяться користувачем.
 
#include <stdio.h>
 
#ifndef Z                       // Z можна задати ключем компіляції -DZ=...
#define Z 5                     // директива препроцесора – макровизначення
#endif
#define SQR(a) ((a)*(a))             // макрос з параметром – квадрат числа
 
// макрос визначення найбільшого з двох
#define MAX(a,b) (((a)>(b))?(a):(b))        // макрос як умовний вираз
// макрос визначення найменшого з двох
#define MIN(a,b) (((a)<(b))?(a):(b))
 
// виведення значення дійсного числа
#define PRINTD(w) puts("control output"); \
                 printf(#w"=%f\n",(double)w)
// використовується символ продовження макроса '\'
// символ '#' перетворює аргумент на рядок
// виведення результату
#define PRINTR(w) puts("result :"); \
                 printf(#w"=%f\n",(double)w)
 
// Обчислює значення виразу w; гілку, що компілюється, визначає значення Z
double calcW(double x, double y)
{
#if Z>3                               // якщо Z > 3, то компілюємо цю гілку
   return MAX(SQR(x+y), SQR(x-Z));
#else                                       // інакше (Z <= 3) – іншу гілку
   return MIN(x*y+y*Z, SQR(Z*x+y*Z));
#endif                               // завершення блоку умовної компіляції
}
 
#ifndef UNIT_TEST           // під час unit-тестування main не компілюється
int main()
{
   puts("Lab 9.2. Using macros and preprocessing directives");
   double x, y, w;                         // змінні для розрахунків
   char ch;                        // відповідь: чи продовжувати виконання
   do
   {
#if Z>3                          // повідомлення про гілку, що компілюється
       puts("branch z>3: w = max((x+y)^2, (x-z)^2)");
#else
       puts("branch z<=3: w = min(xy+yz, (zx+yz)^2)");
#endif
       PRINTD(Z);                       // контрольне виведення значення z
       puts("Input x and y");
       scanf("%lf",&x);                    // введення числа
       PRINTD(x);                          // макрос виведення числа
       scanf("%lf",&y);
       PRINTD(y);
       w = calcW(x,y);                     // обчислення виразу
       PRINTR(w);                          // макрос виведення результату
       puts("Repeat? y /n ");
       scanf(" %c",&ch);
   } while (ch=='y');
   return 0;
}
#endif
